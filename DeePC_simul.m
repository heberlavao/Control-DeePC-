[Ad,Bd,Cd,Dd] = ssdata(sys_teorico_d);
%aplicar retardo
[Aa,Ba, Ca, Da] = anadir_retardo_u(Ad, Bd, Cd, Dd, d);
% nuevo sistema discreto aumentado
sys_delay = ss(Aa,Ba,Ca,Da,T_s);
%crear el sistema discreto_teorico
Ad = sys_delay.A;
Bd = sys_delay.B;
