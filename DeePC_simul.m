      u_data_f = [du_data, du_ini];
      y_ini = y_final(:,end-T_ini+1:end);
      y_data_f = [y_data, y_ini];
      rd = reshape(r_data(:,k-max_samples:k-max_samples+N-1),[],1);
      ref=rd(1);
      ref_s=ref-sigma_y(end);
      r_final = [r_final ref]; %actualiza vector referencia
      tic
      [u, y_pred, sigma_y] = DEEPC_H(u_data_f, y_data_f, u_IV, y_IV, ref_s, umin,umax,y_min,y_max,lambda_g, lambda_y,Q_d,R_d, N, T_ini);
