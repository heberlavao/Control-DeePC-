if T_sw > T_sw_max
    T_sw = T_sw_max;
end
% relacion tiempo PRBS y tiempo simulacion
TTF = round(T_sw/T_s); %cantidad de muestras en cada cambio de PRBS
if TTF==0
    fprintf('error: TTF debe ser igual o mayor a 1 \n');
end
T_sw = TTF*T_s; %recalculo de T_sw para sincronizacion
times = T_sw*Np; % tiempo de la secuencia en segundos
