%% DeePC Controller Setup z=[g,sigma_y]
simulax = max_samples+size(r_data,2)-N-2;
%sistema en espacio de estados de motor DC
J = 0.3795;      % kg·m²
b = 0.006803; % 0.06803; % N·m·s/rad
