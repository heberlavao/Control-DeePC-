    %actualiza vectores de registro
    y_final = [y_final y_1];
    u_final = [u_final uu];
    x_final = [x_final x_1];
    x_1(:, 1) = x_final(:, end);
        
    if k == (max_samples) %iniciales de control iter 1           
      r_final = u_total(1,1:max_samples);
      y_data = y_final(:, end-max_samples+1:end-T_ini);
      y_IV = y_data;
