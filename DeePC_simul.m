      du_data = diff(u_data);%calculo de incrementales historicos
      u_IV = du_data;
    else if k > max_samples
      u_data_o = u_final(:, end-max_samples:end-T_ini); %uno mas par el diff()
      y_data_o = y_final(:, end-max_samples+1:end-T_ini);
      du_data_o =  diff(u_data_o);%calculo de incrementales historicos
      u_ini = u_final(:,end-T_ini:end); 
