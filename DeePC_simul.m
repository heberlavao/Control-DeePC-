%% Simulacion del DeePC
for k = 1:simulax
    %generacion de señal PRBS
    if k==1
         [u_prbs, u_total] = generar_PRBS_para_identificacion(TTF, larg, Amp, u_min, u_max);
    end
    for i = 1:Mpas
      t=1*T_s;
      if mod(k, larg)==0 || k==1 %reinicia bit_prbs
          bit_prbs = 1;
      end  
      if isempty(u_n) %señal de prbs durante la prueba inicial
          uu = u_total(bit_prbs);
      else %señal aplicada a sistema cuando se ha iniciado el control
         uu = u_n(i,:)+ u_final(end);
      end
      bit_prbs = bit_prbs + 1;
      %añadir perturbacion
      if k >= max_samples+100 
          d_k = 1;   % par de carga
      else
          d_k = 0;
      end
      %sistema
        y_1 = Cd * x_1(:, i) + Dd * uu;          
        x_1 = Ad * x_1(:, i) + Bd * uu + E*d_k;  

        x_1(:, i+1) = x_1(:, i); %almacena el ultimo valor calculado en la matriz 
        y_1(:, i) = Cd * x_1(:, i) + 0.7*randn();%adiciona ruido
        Ju = Ju + uu*R_d*uu'; %costo
    end
    %almacena vector de tiempo
    if isempty(t_final)
      t_final = T_s;             
    else
      t_final = [t_final, t_final(end)+T_s];
